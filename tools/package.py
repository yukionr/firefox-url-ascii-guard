"""Build an XPI from an explicit, local-only file list."""

import json
from pathlib import Path
from zipfile import ZIP_DEFLATED, ZipFile

root = Path(__file__).resolve().parents[1]
manifest = json.loads((root / "manifest.json").read_text())
sources = ["src/guard.js", "src/controller.js", "experiments/urlbar/api.js"]
bundle = root / "experiments/urlbar/bundle.js"
bundle.write_text("// Generated by tools/package.py. Edit the source files instead.\n" +
                  "\n".join((root / name).read_text() for name in sources))
files = ["manifest.json", "src/background.js",
         "src/urlbar.css", "experiments/urlbar/schema.json", "experiments/urlbar/bundle.js",
         "icons/guard.svg"]
output = root / "dist" / f"url-ascii-guard-{manifest['version']}.xpi"
output.parent.mkdir(exist_ok=True)
with ZipFile(output, "w", ZIP_DEFLATED) as archive:
    for name in files:
        archive.write(root / name, name)
with ZipFile(output) as archive:
    assert archive.testzip() is None
    assert json.loads(archive.read("manifest.json")) == manifest
print(output)
